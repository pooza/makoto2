module Makoto
  # 曲名から**供給元の但し書き**を落とす（#118）。
  #
  # ⚠⚠ **落とすのは「どの盤に入っていたか」「どのバージョンか」だけ。**曲名そのもの
  # （副題を含む）は触らない。⚠ **`〜勇気はキズナ〜` のような波括りの副題は曲名の一部**
  # なので、**波括りというだけでは落とさない。**
  #
  # ⚠ **`TrackImporter.dedupe_key` とは役割が違う。**あちらは**表記の揺れ**を吸収する
  # （記号・空白・大小）もので、⚠⚠ **括弧の中身は残す。**こちらは**中身のほうを落とす。**
  # 🔴 **`dedupe_key` の側は触らない** — **コーパス全体（4,305 曲）の鍵が動き、同名別曲を
  # 潰す危険が広がる**（サントラのキュー名に同名別曲が多い → `TrackImporter.dedupe_key`）。
  #
  # ⚠ **ここは「どこからが但し書きか」の規則を置く場所**で、⚠⚠ **選曲（#118）と表示
  # （#119）で規則を 2 つ持たない**ためにある。**#119 は `BRACKETS` だけを使う**
  # （表示では版の違いを消したくない ＝ 但し書きの範囲が違う）。
  module TrackName
    # 括弧書き。⚠ **半角・全角が混ざった対でも落とす**（供給元の表記は揃っていない）。
    #
    # ⚠ 実データの形: `(『おかあさんといっしょ』より)` `【ひょうげんあそび】`
    # `[6月]` `(光るパジャマCM曲)` `(花奈〈CV: 宮本 佳那子〉)`
    BRACKETS = /[(（][^()（）]*[)）]|【[^【】]*】|『[^『』]*』|[\[［][^\[\]［］]*[\]］]/

    # 版を指す語。⚠ **`Forever` の `ver` を拾わない**ように、英字が続く形は外す。
    VERSION = /(?:バージョン|ヴァージョン|(?<![[:alpha:]])(?:version|ver)\.?(?![[:alpha:]]))/i

    # 波括りで括られた版の但し書き。⚠ **閉じている形**（`~ロング・イントロ・バージョン~`）
    # と、⚠ **末尾で閉じていない形**（`~ロング・バージョン`）の両方。
    #
    # ⚠ **波括りそのものを目印にしない。**⚠⚠ **`〜SONGBIRD〜`（ライブ名）や
    # `ガンバランスdeダンス ~夢みる奇跡たち~` を削ってしまう。**版を指す語があるときだけ落とす。
    #
    # ⚠ **閉じている形は曲名の途中にも来る**（`~Hybrid ver.~ for the Movie`）ので
    # 末尾に限定しない。⚠⚠ **閉じていない形だけは末尾に限る** — **限らないと、
    # 版の語がどこかにあるだけで後ろが全部消える。**
    VERSION_NOTE = /[〜~～][^〜~～]*#{VERSION}[^〜~～]*(?:[〜~～]|\z)/

    # 感嘆符・疑問符の連なり（#120）。⚠ **全角・半角と `!` `?` を混ぜて 1 つの連なり**
    # として数える（`!?` も 2 つ）。
    MARKS = /[!！?？]+/

    NARROW_MARKS = '!?'.freeze

    WIDE_MARKS = '！？'.freeze

    # 選曲の同一視に使う曲名。⚠ **これを `dedupe_key` に通したものが鍵**になる。
    #
    # ⚠⚠ **落とした結果が空になるものは落とさない**（保険）。曲名が但し書きだけで
    # できていることは無いはずだが、**空の鍵に全部が寄るほうが被害が大きい。**
    def self.base(name)
      return strip_notes(name).presence || name.to_s
    end

    # ⚠ **括弧書きを先に落とす。**⚠⚠ **版の但し書きは括弧の後ろに来ることがある**
    # （`~ロング・バージョン(おかあさんといっしょ)`）ので、逆にすると末尾に当たらない。
    def self.strip_notes(name)
      stripped = name.to_s.gsub(BRACKETS, ' ').gsub(VERSION_NOTE, ' ')
      return squeeze(stripped)
    end

    # 表示に使う曲名（#119）。⚠ **落とすのは括弧書きだけ。**
    #
    # ⚠⚠ **`base` と落とす範囲が違う。**⚠ **選曲では版違いを 1 曲に寄せたいが、
    # 表示では「どの版を歌っているか」を消したくない**（`~ロング・バージョン` は残す）。
    # 🔴 **規則そのもの（`BRACKETS`）は共有する** — **「どこからが括弧書きか」を 2 つ持たない。**
    #
    # ⚠ **落とした結果が空になるものは落とさない**（`base` と同じ保険）。
    def self.display(name)
      return squeeze(name.to_s.gsub(BRACKETS, ' ')).presence || name.to_s
    end

    # 感嘆符・疑問符の見え方を揃える（#120）。⚠ **連なっていれば半角、単発なら全角。**
    #
    # ⚠ **実データはほぼ全部が半角**なので、**単発だと文字が痩せて見える**。⚠⚠ **連なりは
    # 半角のほうが締まる**（`いえイェイ!!`）ので、**数で分ける。**
    #
    # ⚠ **`！` と `？` が混ざった連なり**（`!?`）も 1 つの連なりとして扱う。
    # ⚠⚠ **全角で入っていても同じ結果になる**（供給元の揺れを吸収する）。
    #
    # 🔴 **表示だけ。`dedupe_key` には触らない** — **触ると曲の同一視が動く**
    # （`NOISE` が約物を落とすので鍵は元から同じ → `TrackImporter`）。
    def self.normalize_marks(name)
      return name.to_s.gsub(MARKS) do |run|
        run.size == 1 ? run.tr(NARROW_MARKS, WIDE_MARKS) : run.tr(WIDE_MARKS, NARROW_MARKS)
      end
    end

    def self.squeeze(value)
      return value.gsub(/[[:space:]]+/, ' ').strip
    end
  end
end

module Makoto
  # 投稿先が本文を**再解釈しない**ようにする（#270 のレビュー・2026-09-08）。
  #
  # ## 🔴 直すのは題名ではなく、プラットフォームの読み取り
  #
  # ⚠⚠ **曲名が `#` で始まると、投稿がその名前のタグのタイムラインにも載る。**
  # 実データは `#キボウレインボウ#`（曲名 7 行）で、⚠ **本文は `♪ #キボウレインボウ#`
  # ＝ `#` の直前が空白**なので、投稿先の `HASHTAG_RE` に当たる。
  #
  # 🔴 **これは「MAKOTO が自分で付けるタグは /live/hashtag の 1 つだけ」**
  # （→ config/application.yaml の `mulukhiya` の節・`HashtagSource`）**を、
  # 供給元の曲名が黙って破っている**形。⚠ **意図しない文脈が混ざるのは、
  # それ自体が壊れている**（2026-09-08・オーナー）。
  #
  # ## ⚠ #58 / #123 とは軸が違う
  #
  # | | 何をする | 表示 |
  # | --- | --- | --- |
  # | **#58**（訂正表） | 供給元の**誤記**を直す ＝ **別の題名を主張する** | 変わる |
  # | **#123**（別名表） | どちらも正しいので**鍵だけ**寄せる | 変えない |
  # | 🔴 **ここ** | **題名の主張は変えず**、再解釈だけ止める | ⚠ 区切りが 1 つ増える |
  #
  # ⚠⚠ **「投稿に出る曲名は変えない」（#123）はこれを禁じていない。**あちらは
  # **どの題名を出すか**の話で、こちらは**出した題名をどう読ませるか**の話。
  #
  # ## 🔴 `escape_status` は使わない
  #
  # ⚠ **上流に [`String#escape_status`](ginseng-fediverse) がある**（実体は
  # `Service.sanitize_status`）が、⚠⚠ **`gsub!(/[@#]/, '\0 ')` で `#` `@` を
  # **無条件に全部**置換する** — 上流のテストも `IDOLM@STER` → `IDOLM@ STER` を
  # 期待値にしている。
  #
  # 🔴 **実データではそれが害になる。**⚠ **`@` を含むのは曲名 12 行・アルバム名 8 行**
  # で、⚠⚠ **すべて `H@ppy Together!!!` 系＝ `@` の直前が `H`（語中文字）なので、
  # 投稿先の `MENTION_RE` に 1 件も当たらない。**無毒化の必要が無いのに
  # `H@ ppy` に変わる。
  #
  # ⚠ **だから「実際にリンク化する箇所だけ」を狙う**（この module）。
  # 🔴 **上流をどうするかは [`ginseng-fediverse#273`](https://github.com/pooza/ginseng-fediverse/issues/273)
  # に切り出した**（区切りを ZWSP へ寄せるか、という判断も含めて先送り）。
  #
  # ## ⚠⚠ 区切りは半角スペース。ZWSP にしない
  #
  # ⚠ **効き目は同等**（実測。`HASHTAG_NAME_PAT` は `[[:word:]_]` 始まりで、
  # `HASHTAG_SEPARATORS` に入っているのは ZWNJ `‌` ＝ ZWSP ではない）。
  #
  # 🔴 **ZWSP は「壊していないように見せる」だけ**で、⚠⚠ **コピペ・検索・他実装へ
  # 見えない文字が付いて回る。**⚠ **スペースなら、次に読む人が「なぜここに空白が」
  # と辿れる**（このコメントに辿り着ける）。
  module StatusText
    # 🔴 **判定の正本は投稿先**（`pooza/mastodon` の `stable/4.7/delmulin`）。
    #
    # ⚠ `app/models/tag.rb:44` — `HASHTAG_RE = /(?<=^|[[:space:]])[#＃](...)/`
    #
    # ⚠⚠ **`＃`（全角）も対象**なので、**全角へ寄せる案は使えない。**
    # ⚠ **`^` は行頭**（本文は複数行で、アルバム名と名義は行頭に来る）。
    #
    # 🔴 **後続は `[[:word:]]` だけを見る**（**上流の `HASHTAG_NAME_PAT` を写さない**）。
    # ⚠⚠ **上流のどの分岐も `[[:word:]_]` で始まる**ので、**これは上流の当たる集合を
    # 必ず含む** — ⚠ **数字だけの `#123` を上流は拾わないが、こちらは区切りを入れる**
    # （**取りこぼすより広く取るほうを選ぶ**）。⚠⚠ **上流の規則を写すと、向こうが
    # 動いた日に静かにずれる。**
    HASHTAG_SIGIL = /(?<=^|[[:space:]])[#＃](?=[[:word:]])/

    # ⚠ `app/models/account.rb:75-76` —
    # `USERNAME_RE = /[a-z0-9_]+([.-]+[a-z0-9_]+)*/i`
    # `MENTION_RE  = %r{(?<![=/[:word:]])@((USERNAME_RE)...)}`
    #
    # 🔴 **直前が `=` `/` 語中文字なら当たらない** — ⚠⚠ **`H@ppy Together!!!` が
    # 無傷で通るのはここ。**⚠ **後続は ASCII の英数字と `_` だけ**（日本語が続く
    # `@` はメンションにならない）。
    MENTION_SIGIL = %r{(?<![=/[:word:]])@(?=[A-Za-z0-9_])}

    SEPARATOR = ' '.freeze

    # ⚠ **リンク化する `#` `@` の後ろに区切りを 1 つ入れる。**
    #
    # 🔴 **当てるのは組み上げた本文**（→ `TrackPresenter#to_s`）。⚠⚠ **タグになるかは
    # 「その文字が本文のどこに居るか」で決まる**ので、**欄ごとに当てても判定できない**
    # （アルバム名と名義は行頭に来る ＝ 直前が改行）。
    #
    # ⚠ **`HashtagSource` が足すタグは通らない**（あちらは `to_s` の**後**で足す）。
    def self.escape_unintended(text)
      return text if text.blank?
      escaped = text.gsub(HASHTAG_SIGIL) {|sigil| sigil + SEPARATOR}
      return escaped.gsub(MENTION_SIGIL) {|sigil| sigil + SEPARATOR}
    end
  end
end
